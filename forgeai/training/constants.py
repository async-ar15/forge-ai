"""Training service constants and defaults with explicit operational intent."""

from __future__ import annotations

import os
from enum import StrEnum


class TrainingConfigKey(StrEnum):
    """Environment keys used to configure training orchestration/runtime."""

    RAY_ADDRESS = "TRAINING_RAY_ADDRESS"
    RETRAINING_LABEL_THRESHOLD = "RETRAINING_LABEL_THRESHOLD"
    RETRAINING_REWARD_BLEND_ALPHA = "RETRAINING_REWARD_BLEND_ALPHA"
    REGRESSION_CHECK_INTERVAL_SECONDS = "REGRESSION_CHECK_INTERVAL_SECONDS"


# rank=16 is the standard LoRA default; higher rank captures more task-specific
# information at the cost of more trainable parameters and memory.
