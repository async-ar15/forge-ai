DEFAULT_LORA_ALPHA = 32.0
DEFAULT_LORA_DROPOUT = 0.1
DEFAULT_TARGET_MODULES = ["q_proj", "v_proj"]
DEFAULT_LEARNING_RATE = 2e-4
DEFAULT_NUM_EPOCHS = 3
DEFAULT_BATCH_SIZE = 4
DEFAULT_GRADIENT_ACCUMULATION_STEPS = 4
DEFAULT_MAX_SEQ_LEN = 2048
DEFAULT_WARMUP_STEPS = 100
DEFAULT_SAVE_STEPS = 500
DEFAULT_EVAL_STEPS = 500
DEFAULT_USE_QLORA = False
DEFAULT_RETRAINING_LABEL_THRESHOLD = int(
    os.environ.get(TrainingConfigKey.RETRAINING_LABEL_THRESHOLD, "1000")
)
DEFAULT_RETRAINING_REWARD_BLEND_ALPHA = float(
    os.environ.get(TrainingConfigKey.RETRAINING_REWARD_BLEND_ALPHA, "0.7")
)
DEFAULT_REGRESSION_CHECK_INTERVAL_SECONDS = int(
    os.environ.get(TrainingConfigKey.REGRESSION_CHECK_INTERVAL_SECONDS, "3600")
)
GRADIENT_NORM_WARNING_THRESHOLD = 10.0


